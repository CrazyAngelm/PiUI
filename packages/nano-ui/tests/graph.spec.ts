import { readFileSync } from 'node:fs';
import { createHash } from 'node:crypto';
import { test, expect } from './browserFixture';

interface GraphFixture {
  mount(document: string): Promise<string>;
  conflict(): void;
  loseNextAcknowledgement(): void;
  mountSecond(language: 'en' | 'ru'): void;
  allowSave(): void;
  calls(): { id: string; expectedRevision: number | null; document: string }[];
  appearance(value: 'light' | 'dark' | 'system'): void;
  dirty(): boolean;
  dispose(): Promise<void>;
}
declare global { interface Window { nanoGraphFixture: GraphFixture } }

const fixture = readFileSync(new URL('../../../examples/systems/structured-review.piui.json', import.meta.url), 'utf8');

test('shared graph keeps the host isolated and preserves a conflicting draft through import, save and reload', async ({ page }, testInfo) => {
  const pageErrors: string[] = [];
  page.on('pageerror', error => pageErrors.push(error.message));
  await page.goto('/tests/host.html');
  await page.waitForFunction(() => typeof window.nanoGraphFixture?.mount === 'function');
  expect(await page.evaluate(() => 'process' in window)).toBe(false);
  const published = readFileSync(new URL('../dist/nano-graph.js', import.meta.url));
  const served = await (await page.request.get('/dist/nano-graph.js')).body();
  expect(createHash('sha256').update(served).digest('hex')).toBe(createHash('sha256').update(published).digest('hex'));
  const id = await page.evaluate(document => window.nanoGraphFixture.mount(document), fixture);
  const saved = page.getByRole('combobox', { name: 'Saved pipelines', exact: true });
  await expect(saved.locator('option')).toHaveCount(2);
  await saved.selectOption(id);
  const name = page.getByLabel('Pipeline name', { exact: true });
  await expect(name).toHaveValue(JSON.parse(fixture).name);
  await expect(page.locator('.svelte-flow__node-agent')).toHaveCount(JSON.parse(fixture).agents.length);
  await expect(page.locator('body')).toHaveCSS('background-color', 'rgb(250, 240, 230)');
  await expect(page.locator('html')).toHaveAttribute('lang', 'fr');
  expect(await page.evaluate(() => getComputedStyle(document.documentElement).getPropertyValue('--piui-bg').trim())).toBe('');
  await expect(page.locator('.nano-graph-root')).toHaveCSS('--piui-bg', '#ebefee');
  await page.screenshot({ path: testInfo.outputPath('shared-graph-light.png'), fullPage: true, animations: 'disabled' });
  await page.evaluate(() => window.nanoGraphFixture.appearance('dark'));
  await expect(page.locator('.nano-graph-root')).toHaveCSS('--piui-bg', '#101513');
  await expect(page.locator('html')).toHaveAttribute('data-theme', 'light');
  await expect(page.locator('body')).toHaveCSS('background-color', 'rgb(250, 240, 230)');
  await page.getByRole('button', { name: 'Add agent', exact: true }).press('Enter');
  await expect(page.locator('.svelte-flow__node-agent')).toHaveCount(JSON.parse(fixture).agents.length + 1);
  await page.getByRole('button', { name: 'Undo', exact: true }).press('Enter');
  await expect(page.locator('.svelte-flow__node-agent')).toHaveCount(JSON.parse(fixture).agents.length);
  await page.locator('.svelte-flow__node-agent').first().focus();
  await page.locator('.svelte-flow__node-agent').first().press('Enter');
  const task = page.getByLabel('Task', { exact: true });
  await task.fill('Edited through the shared canvas');
  expect(await page.evaluate(() => window.nanoGraphFixture.dirty())).toBe(true);
  await task.press('Tab');
  await expect(page.locator('.svelte-flow__node-agent').first()).toContainText('Edited through the shared canvas');
  await page.getByRole('button', { name: 'Undo', exact: true }).click();
  await expect(task).toHaveValue(JSON.parse(fixture).agents[0].task);
  await page.screenshot({ path: testInfo.outputPath('shared-graph-dark.png'), fullPage: true, animations: 'disabled' });
  await page.locator('input[type="file"]').setInputFiles({ name: 'invalid.piui.json', mimeType: 'application/json', buffer: Buffer.from('{"unknown":"must preserve draft"}') });
  await expect(page.getByRole('alert')).toBeVisible();
  await expect(name).toHaveValue(JSON.parse(fixture).name);
  expect(await page.evaluate(() => window.nanoGraphFixture.calls())).toHaveLength(0);

  await name.fill('Shared web draft');
  await name.press('Tab');
  await page.evaluate(() => window.nanoGraphFixture.conflict());
  await page.getByRole('button', { name: 'Save', exact: true }).click();
  await expect(page.getByRole('alert')).toContainText('changed elsewhere');
  await expect(name).toHaveValue('Shared web draft');
  await expect.poll(() => page.evaluate(() => window.nanoGraphFixture.dirty())).toBe(true);
  await page.getByRole('button', { name: 'Keep as a new draft', exact: true }).click();
  await page.evaluate(() => window.nanoGraphFixture.allowSave());
  await page.getByRole('button', { name: 'Save', exact: true }).click();
  await expect(page.getByRole('status').filter({ hasText: 'Pipeline saved.' })).toBeVisible();
  const calls = await page.evaluate(() => window.nanoGraphFixture.calls());
  expect(calls[1].id).not.toBe(id);
  expect(calls[1].expectedRevision).toBeNull();
  expect(JSON.parse(calls[1].document).agents[1].review).toEqual(JSON.parse(fixture).agents[1].review);

  await page.getByText('Portable document', { exact: true }).click();
  const document = page.getByRole('textbox', { name: 'Portable system JSON', exact: true });
  await document.fill('{"unsupported":"must preserve draft"}');
  await expect(name).toBeDisabled();
  await expect(page.getByRole('button', { name: 'Add agent', exact: true })).toBeDisabled();
  await page.getByRole('button', { name: 'Apply document', exact: true }).click();
  await expect(page.getByRole('alert')).toBeVisible();
  await expect(name).toHaveValue('Shared web draft');
  await page.getByRole('button', { name: 'Reload', exact: true }).click();
  await page.getByRole('button', { name: 'Discard changes', exact: true }).click();
  await expect(name).toHaveValue('Shared web draft');
  await expect(document).toContainText('');
  await expect.poll(async () => JSON.parse(await document.inputValue()).name).toBe('Shared web draft');
  await page.getByRole('button', { name: 'Zoom in', exact: true }).hover();
  const tooltip = page.locator('.piui-tooltip');
  await expect(tooltip).toBeVisible();
  await expect(page.locator('.nano-graph-root .piui-tooltip')).toBeVisible();
  await expect(page.getByRole('button', { name: 'Zoom in', exact: true })).toHaveAttribute('aria-describedby', await tooltip.getAttribute('id') ?? '');
  await page.evaluate(() => window.nanoGraphFixture.dispose());
  await expect(page.locator('#graph')).toBeEmpty();
  await expect(page.locator('.piui-tooltip')).toHaveCount(0);
  expect(pageErrors).toEqual([]);
});

test('simultaneous English and Russian mounts isolate language and support reserved-looking portable IDs', async ({ page }) => {
  const errors: string[] = [];
  page.on('pageerror', error => errors.push(error.message));
  const document = JSON.parse(fixture);
  const before = document.agents.map((agent: { id: string }) => agent.id);
  const ids = ['__start', '__output'];
  document.agents.forEach((agent: { id: string; review?: { retryFromStepId: string }; inputBindings?: { sourceStepId: string }[] }, index: number) => {
    agent.id = ids[index];
    if (agent.review) agent.review.retryFromStepId = ids[before.indexOf(agent.review.retryFromStepId)];
    agent.inputBindings?.forEach(binding => { binding.sourceStepId = ids[before.indexOf(binding.sourceStepId)]; });
  });
  document.orchestrator = ids[before.indexOf(document.orchestrator)];
  document.connections.forEach((edge: { from: string; to: string }) => { edge.from = ids[before.indexOf(edge.from)]; edge.to = ids[before.indexOf(edge.to)]; });
  await page.goto('/tests/host.html');
  await page.waitForFunction(() => Boolean(window.nanoGraphFixture));
  const id = await page.evaluate(text => window.nanoGraphFixture.mount(text), JSON.stringify(document));
  await page.evaluate(() => window.nanoGraphFixture.mountSecond('ru'));
  const english = page.locator('#graph'), russian = page.locator('#second');
  await expect(english.getByRole('button', { name: 'Add agent', exact: true })).toBeVisible();
  await expect(russian.getByRole('button', { name: 'Добавить агента', exact: true })).toBeVisible();
  await english.getByRole('combobox', { name: 'Saved pipelines', exact: true }).selectOption(id);
  await russian.getByRole('combobox', { name: 'Сохранённые пайплайны', exact: true }).selectOption(id);
  await expect(english.locator('.svelte-flow__node-agent')).toHaveCount(2);
  await expect(english.locator('.svelte-flow__node-start')).toHaveCount(1);
  await expect(english.locator('.svelte-flow__node-output')).toHaveCount(1);
  const graphIds = await english.locator('.svelte-flow__node').evaluateAll(nodes => nodes.map(node => node.getAttribute('data-id')));
  expect(new Set(graphIds).size).toBe(graphIds.length);
  await english.locator('.svelte-flow__node-agent[data-id="__start"]').press('Enter');
  await expect(english.getByLabel('Task', { exact: true })).toHaveValue(document.agents[0].task);
  await english.getByRole('button', { name: 'Delete selection', exact: true }).click();
  await expect(english.locator('.svelte-flow__node-agent')).toHaveCount(1);
  await expect(russian.locator('.svelte-flow__node-agent')).toHaveCount(2);
  await expect(page.locator('html')).toHaveAttribute('lang', 'fr');
  await expect(english.getByRole('button', { name: 'Add agent', exact: true })).toBeVisible();
  expect(errors).toEqual([]);
});

test('lost create acknowledgement exposes conflict recovery independently from validation errors', async ({ page }) => {
  await page.goto('/tests/host.html');
  await page.waitForFunction(() => Boolean(window.nanoGraphFixture));
  await page.evaluate(document => window.nanoGraphFixture.mount(document), fixture);
  await page.locator('input[type="file"]').setInputFiles({ name: 'draft.piui.json', mimeType: 'application/json', buffer: Buffer.from(fixture) });
  await page.evaluate(() => window.nanoGraphFixture.loseNextAcknowledgement());
  await page.getByRole('button', { name: 'Save', exact: true }).click();
  await expect(page.getByRole('alert')).toContainText('Could not confirm');
  await expect(page.getByRole('button', { name: 'Reload', exact: true })).toBeEnabled();
  await page.getByLabel('Pipeline name', { exact: true }).fill('Edited after unconfirmed create');
  await page.getByRole('button', { name: 'Save', exact: true }).click();
  await expect(page.getByRole('alert')).toContainText('changed elsewhere');
  await page.getByText('Portable document', { exact: true }).click();
  await page.getByRole('button', { name: 'Apply document', exact: true }).click();
  await expect(page.getByRole('button', { name: 'Keep as a new draft', exact: true })).toBeVisible();
  await page.getByRole('button', { name: 'Reload', exact: true }).click();
  await page.getByRole('button', { name: 'Discard changes', exact: true }).click();
  await expect.poll(() => page.evaluate(() => window.nanoGraphFixture.dirty())).toBe(false);
  await expect(page.getByRole('button', { name: 'Keep as a new draft', exact: true })).toHaveCount(0);
});
